# disk_check.py
# Скрипт для моніторингу дискового простору сервера

disk_name = input("Введіть назву диска (наприклад, /dev/sda1): ")
total_gb = int(input("Введіть загальний розмір диска (ГБ): "))
used_gb = float(input("Введіть використаний простір (ГБ): "))

# Обчислення відсотка використаного місця
used_percent = (used_gb / total_gb) * 100

print("\n--- ЗВІТ ПРО ДИСКОВИЙ ПРОСТІР ---")
print(f"Диск: {disk_name}")
print(f"Загальний об'єм: {total_gb} ГБ")
print(f"Використано: {used_gb} ГБ ({used_percent:.1f}%)")

# Перевірка на переповнення
if used_percent > 80:
    print("⚠️ ПОПЕРЕДЖЕННЯ: Диск заповнений більше ніж на 80%!")
else:
    print("✅ Стан диска в нормі.")
